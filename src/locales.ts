/**
 * Pick the best supported locale for a list of preferred languages
 * (navigator.languages in the browser, parsed Accept-Language on the server).
 * Exact match first ("pt-BR" → "pt-br" if we ever add it), then the base
 * language ("pt-BR" → "pt"). Returns DEFAULT_LOCALE when nothing matches.
 */
export function resolveLocale(preferred: readonly string[] | undefined | null): string {
  if (!preferred) return DEFAULT_LOCALE;
  for (const raw of preferred) {
    if (!raw) continue;
    const tag = raw.toLowerCase().trim();
    if (tag in LOCALES || tag === DEFAULT_LOCALE) return tag;
    const base = tag.split(/[-_]/)[0];
    if (base in LOCALES || base === DEFAULT_LOCALE) return base;
  }
  return DEFAULT_LOCALE;
}

/** Parse an Accept-Language header into an ordered list of language tags. */
export function parseAcceptLanguage(header: string | null | undefined): string[] {
  if (!header) return [];
  return header
    .split(",")
    .map((part) => {
      const [tag, ...params] = part.trim().split(";");
      const q = params.map((p) => p.trim()).find((p) => p.startsWith("q="));
      const weight = q ? Number(q.slice(2)) : 1;
      return { tag: tag.trim(), weight: Number.isFinite(weight) ? weight : 0 };
    })
    .filter((x) => x.tag && x.tag !== "*" && x.weight > 0)
    .sort((a, b) => b.weight - a.weight)
    .map((x) => x.tag);
}

